/// Phone-maker specific steps so background reminders and floating azkar keep working.
String? deviceTip(String manufacturer) {
  final m = manufacturer.toLowerCase();
  if (m.contains('xiaomi') || m.contains('redmi') || m.contains('poco')) {
    return 'في هواتف شاومي: الإعدادات ← التطبيقات ← أذكار المسلم ← فعّل «التشغيل التلقائي»، ومن «توفير البطارية» اختر «بلا قيود»، ومن «أذونات أخرى» فعّل «عرض النوافذ المنبثقة أثناء التشغيل في الخلفية».';
  }
  if (m.contains('oppo') || m.contains('realme') || m.contains('oneplus')) {
    return 'في هواتف ريلمي وأوبو: فعّل «التشغيل التلقائي» لأذكار المسلم، ومن «استخدام البطارية» فعّل «السماح بالنشاط في الخلفية». ويُفضّل قفل التطبيق في قائمة التطبيقات الأخيرة (اسحبه لأسفل) حتى لا يُغلق عند تنظيفها.';
  }
  if (m.contains('vivo') || m.contains('iqoo')) {
    return 'في هواتف فيفو: الإعدادات ← البطارية ← استهلاك الطاقة في الخلفية ← اسمح لأذكار المسلم، وفعّل «التشغيل التلقائي».';
  }
  if (m.contains('samsung')) {
    return 'في هواتف سامسونج: الإعدادات ← البطارية ← حدود استخدام الخلفية ← أضف أذكار المسلم إلى «التطبيقات التي لا تدخل في وضع السكون أبدًا».';
  }
  if (m.contains('huawei') || m.contains('honor')) {
    return 'في هواتف هواوي: الإعدادات ← البطارية ← تشغيل التطبيقات ← أذكار المسلم ← «إدارة يدويًا» وفعّل التشغيل التلقائي والتشغيل في الخلفية.';
  }
  if (m.isEmpty) return null;
  return 'حتى لا يوقف هاتفك التذكيرات: من إعدادات البطارية اجعل أذكار المسلم «غير مقيّد»، وفعّل التشغيل التلقائي إن وُجد.';
}
